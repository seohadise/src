const isIranianHoliday = (date) => {
  const d = date instanceof Date ? date : new Date(date);

  // ساخت کلید YYYY-MM-DD
  const key = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

  // 1. بررسی در لیست ثابت سال‌های ۱۴۰۴-۱۴۰۶ (داده دقیق از time.ir)
  if (allHolidays[key]) {
    return allHolidays[key];
  }

  // 2. بررسی تعطیلات ثابت شمسی (برای همه سال‌ها)
  const { jm, jd } = gregorianToJalali(d.getFullYear(), d.getMonth() + 1, d.getDate());
  const fixedMatch = fixedJalaliHolidays.find((h) => h.m === jm && h.d === jd);
  if (fixedMatch) return fixedMatch.name;

  // 3. بررسی تعطیلات قمری (فقط برای سال‌های خارج از لیست ثابت)
  // برای سال‌های ۱۴۰۴-۱۴۰۶ داده دقیق time.ir استفاده شده، لذا لایه قمری لازم نیست
  // تقویم islamic-umalqura حدود یک روز با تقویم رسمی ایران اختلاف دارد
  // بنابراین تاریخ قمری روز بعد را بررسی می‌کنیم تا با تقویم رسمی ایران مطابقت کند
  const timestamp = d.getTime();
  const hardcodedStart = new Date("2025-03-21").getTime();
  const hardcodedEnd = new Date("2028-03-20").getTime();
  if (timestamp < hardcodedStart || timestamp > hardcodedEnd) {
    // بررسی تاریخ قمری روز بعد (چون umalqura یک روز عقب‌تر از تقویم رسمی ایران است)
    const nextDay = new Date(d);
    nextDay.setDate(nextDay.getDate() + 1);
    const hijriNext = gregorianToHijri(nextDay);
    if (hijriNext) {
      const lunarMatchNext = lunarHolidays.find((h) => h.m === hijriNext.hm && h.d === hijriNext.hd);
      if (lunarMatchNext) return lunarMatchNext.name;
    }
    // همچنین بررسی تاریخ قمری خود روز (در صورت عدم اختلاف برای برخی تاریخ‌ها)
    const hijri = gregorianToHijri(d);
    if (hijri) {
      const lunarMatch = lunarHolidays.find((h) => h.m === hijri.hm && h.d === hijri.hd);
      if (lunarMatch) return lunarMatch.name;
    }
  }

  return null;
};

export default isIranianHoliday;
